#include<iostream>
using namespace std;
int main(){
	float num1,num2;
	cout<<"====== Input ======="<<endl;
	cout<<"Enter Num1 = ";cin>>num1;
	cout<<"Enter Num2 = ";cin>>num2;
	
	cout<<"====== Output ======="<<endl;
	cout<<"Num1 = "<<num1<<endl;
	cout<<"Num2 = "<<num2<<endl;
	cout<<num1<<"+"<<num2<<"= "<<(num1+num2)<<endl;
	cout<<num1<<"-"<<num2<<"= "<<(num1-num2)<<endl;
	cout<<num1<<"*"<<num2<<"= "<<(num1*num2)<<endl;
	cout<<num1<<"/"<<num2<<"= "<<(num1/num2)<<endl;
	
	
	return 0;
}