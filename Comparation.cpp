//Comparation Operator
// x=2,y=2 =>x==y = 1
// x=2,y=2 =>x!=y = 0
// x=2,y=2 =>x<y = 0
// x=3,y=2 =>x>y = 1
// x=3,y=2 =>x<=y = 0
// x=3,y=2 =>x>=y = 1
#include<iostream>
using namespace std;
int main(){
	cout<<"2 == 2 = "<<(2==2)<<endl;
	cout<<"2 != 2 = "<<(2!=2)<<endl;
	cout<<"2 < 2 = "<<(2<2)<<endl;
	cout<<"2 > 2 = "<<(2>2)<<endl;
	cout<<"2 <= 2 = "<<(2<=2)<<endl;
	cout<<"2 >= 2 = "<<(2>=2)<<endl;
	return 0;
}




